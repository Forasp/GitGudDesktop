# Generates BragiUsage.png + BragiUsage.xml, the usage circle's rings
# (imageset "Bragi-Usage", scripts/bragi/usage.lua). White, so a Gitgud/Icon
# tints them (IconColour). Every image is 32x32 with the ring centred, so
# the rings stack in one place:
#
#   Track1..3      a whole ring: 1 the outer (context), 2 the middle
#                  (five-hour limit), 3 the inner (weekly limit)
#   Arc<r>-<n>     ring r filled to n * 2 percent (n 1..50), clockwise
#                  from the top
#
# Run it after editing: powershell -ExecutionPolicy Bypass -File make-usage-rings.ps1
Add-Type -AssemblyName System.Drawing

$Size = 32
$Steps = 50
$Rings = @(
    @{ Radius = 13.6; Width = 2.4 },
    @{ Radius = 9.2; Width = 2.2 },
    @{ Radius = 4.8; Width = 2.2 }
)
$Cols = 16
$Count = $Rings.Count * ($Steps + 1)
$W = $Cols * $Size
$H = [math]::Ceiling($Count / $Cols) * $Size

$bmp = New-Object System.Drawing.Bitmap($W, $H, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
$g = [System.Drawing.Graphics]::FromImage($bmp)
$g.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
$g.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
$g.Clear([System.Drawing.Color]::Transparent)

$regions = New-Object System.Collections.ArrayList
$slot = 0

function Next($name) {
    $x = ($script:slot % $Cols) * $Size
    $y = [math]::Floor($script:slot / $Cols) * $Size
    $script:slot++
    [void]$regions.Add(@{ Name = $name; X = $x; Y = $y; W = $Size; H = $Size })
    return @($x, $y)
}

function Pen($w) {
    $p = New-Object System.Drawing.Pen([System.Drawing.Color]::White, $w)
    $p.StartCap = [System.Drawing.Drawing2D.LineCap]::Round
    $p.EndCap = [System.Drawing.Drawing2D.LineCap]::Round
    return $p
}

for ($r = 0; $r -lt $Rings.Count; $r++) {
    $ring = $Rings[$r]
    $d = 2 * $ring.Radius
    $o = $Size / 2 - $ring.Radius
    $at = Next ("Track" + ($r + 1))
    $g.DrawEllipse((Pen $ring.Width), [single]($at[0] + $o), [single]($at[1] + $o), [single]$d, [single]$d)
    for ($n = 1; $n -le $Steps; $n++) {
        $at = Next ("Arc" + ($r + 1) + "-" + $n)
        $sweep = 360.0 * $n / $Steps
        if ($n -eq $Steps) {
            $g.DrawEllipse((Pen $ring.Width), [single]($at[0] + $o), [single]($at[1] + $o), [single]$d, [single]$d)
        } else {
            $g.DrawArc((Pen $ring.Width), [single]($at[0] + $o), [single]($at[1] + $o), [single]$d, [single]$d, -90, [single]$sweep)
        }
    }
}

$g.Dispose()
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$bmp.Save((Join-Path $here "BragiUsage.png"), [System.Drawing.Imaging.ImageFormat]::Png)
$bmp.Dispose()

$xml = New-Object System.Text.StringBuilder
[void]$xml.AppendLine('<?xml version="1.0" encoding="UTF-8"?>')
[void]$xml.AppendLine('<!-- BragiUsage.xml - the usage circle''s rings. Generated by make-usage-rings.ps1; edit that, not this. -->')
[void]$xml.AppendLine('<Imageset version="2" name="Bragi-Usage" imagefile="BragiUsage.png" resourceGroup="ui-imagesets" nativeHorzRes="1280" nativeVertRes="720" autoScaled="false">')
foreach ($r in $regions) {
    [void]$xml.AppendLine(('    <Image name="{0}" xPos="{1}" yPos="{2}" width="{3}" height="{4}"/>' -f $r.Name, $r.X, $r.Y, $r.W, $r.H))
}
[void]$xml.AppendLine('</Imageset>')
[System.IO.File]::WriteAllText((Join-Path $here "BragiUsage.xml"), $xml.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Wrote BragiUsage.png and BragiUsage.xml"
