# Generates BragiPanel.png + BragiPanel.xml, the session panel's images
# (imageset "Bragi-Panel", scripts/bragi/sidepanel.lua). White, so a
# Gitgud/Icon tints them (IconColour) or inline markup does ([colour]).
#
#   PanelToggle   24x24: the header button that shows and hides the panel
#   16x16 row icons: Computer Folder File Agent Terminal Stop Check Cross
#
# Run it after editing: powershell -ExecutionPolicy Bypass -File make-panel-icons.ps1
Add-Type -AssemblyName System.Drawing

$W = 192; $H = 24
$bmp = New-Object System.Drawing.Bitmap($W, $H, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
$g = [System.Drawing.Graphics]::FromImage($bmp)
$g.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
$g.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
$g.Clear([System.Drawing.Color]::Transparent)

$regions = New-Object System.Collections.ArrayList
$white = "FFFFFF"

function C($hex) {
    return [System.Drawing.ColorTranslator]::FromHtml("#" + $hex)
}
function Pen($hex, $w) {
    $p = New-Object System.Drawing.Pen((C $hex), $w)
    $p.StartCap = [System.Drawing.Drawing2D.LineCap]::Round
    $p.EndCap = [System.Drawing.Drawing2D.LineCap]::Round
    $p.LineJoin = [System.Drawing.Drawing2D.LineJoin]::Round
    return $p
}
function Brush($hex) { return New-Object System.Drawing.SolidBrush((C $hex)) }
function Line($ox, $oy, $x0, $y0, $x1, $y1, $w) {
    $g.DrawLine((Pen $white $w), [single]($ox + $x0), [single]($oy + $y0), [single]($ox + $x1), [single]($oy + $y1))
}
function Poly($ox, $oy, $points, $w) {
    $pts = @()
    for ($k = 0; $k -lt $points.Count; $k += 2) {
        $pts += New-Object System.Drawing.PointF(($ox + $points[$k]), ($oy + $points[$k + 1]))
    }
    $g.DrawPolygon((Pen $white $w), [System.Drawing.PointF[]]$pts)
}
function RoundRect($ox, $oy, $x, $y, $w, $h, $r, $fill, $stroke, $sw) {
    $path = New-Object System.Drawing.Drawing2D.GraphicsPath
    $x = $ox + $x; $y = $oy + $y; $d = 2 * $r
    $path.AddArc([single]$x, [single]$y, [single]$d, [single]$d, 180, 90)
    $path.AddArc([single]($x + $w - $d), [single]$y, [single]$d, [single]$d, 270, 90)
    $path.AddArc([single]($x + $w - $d), [single]($y + $h - $d), [single]$d, [single]$d, 0, 90)
    $path.AddArc([single]$x, [single]($y + $h - $d), [single]$d, [single]$d, 90, 90)
    $path.CloseFigure()
    if ($fill) { $g.FillPath((Brush $fill), $path) }
    if ($stroke) { $g.DrawPath((Pen $stroke $sw), $path) }
}
function Add($name, $x, $y, $w, $h) {
    [void]$regions.Add(@{ Name = $name; X = $x; Y = $y; W = $w; H = $h })
}

# ---- 24x24: the header button ----------------------------------------------
# The sessions sidebar's icon, mirrored: the panel is on the right.
RoundRect 0 0 3.5 4.5 17 15 2.5 $null $white 1.8
Line 0 0 14.5 5 14.5 19 1.8
Add "PanelToggle" 0 0 24 24

# ---- 16x16 row icons, from x 26 -----------------------------------------------
$names = @("Computer", "Folder", "File", "Agent", "Terminal", "Stop", "Check", "Cross")
for ($i = 0; $i -lt $names.Count; $i++) {
    $ox = 26 + $i * 18; $oy = 4
    Add $names[$i] $ox $oy 16 16
    switch ($names[$i]) {
        "Computer" {
            RoundRect $ox $oy 1.5 2.5 13 8.5 1.5 $null $white 1.4
            Line $ox $oy 8 11.5 8 13.5 1.4
            Line $ox $oy 5 13.5 11 13.5 1.4
        }
        "Folder" {
            Poly $ox $oy @(1.5, 3.5, 6, 3.5, 7.5, 5, 14.5, 5, 14.5, 12.5, 1.5, 12.5) 1.4
        }
        "File" {
            Poly $ox $oy @(3.5, 1.5, 9.5, 1.5, 12.5, 4.5, 12.5, 14.5, 3.5, 14.5) 1.4
            Line $ox $oy 9.5 1.5 9.5 4.5 1.2
            Line $ox $oy 9.5 4.5 12.5 4.5 1.2
        }
        "Agent" {
            Poly $ox $oy @(2, 3, 14, 3, 14, 10.5, 7, 10.5, 3.5, 13.5, 3.5, 10.5, 2, 10.5) 1.4
        }
        "Terminal" {
            Line $ox $oy 3 4.5 6.5 8 1.5
            Line $ox $oy 6.5 8 3 11.5 1.5
            Line $ox $oy 8.5 12 13.5 12 1.5
        }
        "Stop" {
            $g.DrawEllipse((Pen $white 1.4), [single]($ox + 1.5), [single]($oy + 1.5), [single]13, [single]13)
            RoundRect $ox $oy 5.5 5.5 5 5 1 $white $null 0
        }
        "Check" {
            Line $ox $oy 3 8.5 6.5 12 1.6
            Line $ox $oy 6.5 12 13 4.5 1.6
        }
        "Cross" {
            Line $ox $oy 4 4 12 12 1.6
            Line $ox $oy 12 4 4 12 1.6
        }
    }
}

$g.Dispose()
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$bmp.Save((Join-Path $here "BragiPanel.png"), [System.Drawing.Imaging.ImageFormat]::Png)
$bmp.Dispose()

$xml = New-Object System.Text.StringBuilder
[void]$xml.AppendLine('<?xml version="1.0" encoding="UTF-8"?>')
[void]$xml.AppendLine('<!-- BragiPanel.xml - the session panel''s images. Generated by make-panel-icons.ps1; edit that, not this. -->')
[void]$xml.AppendLine('<Imageset version="2" name="Bragi-Panel" imagefile="BragiPanel.png" resourceGroup="ui-imagesets" nativeHorzRes="1280" nativeVertRes="720" autoScaled="false">')
foreach ($r in $regions) {
    [void]$xml.AppendLine(('    <Image name="{0}" xPos="{1}" yPos="{2}" width="{3}" height="{4}"/>' -f $r.Name, $r.X, $r.Y, $r.W, $r.H))
}
[void]$xml.AppendLine('</Imageset>')
[System.IO.File]::WriteAllText((Join-Path $here "BragiPanel.xml"), $xml.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Wrote BragiPanel.png and BragiPanel.xml"
